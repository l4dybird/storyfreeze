#!/usr/bin/env node
// Generates Scale.stories.jsx with deliberately uneven per-story cost.
//
// The stories must be *literal* named exports: Storybook's CSF indexer and
// StoryFreeze's viewport/cost indexer both read them statically, so anything
// built at runtime would carry no tags.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const light = 240; // cheap, no delay, no variants
const delayed = 30; // static delay
const multiVariant = 20; // three viewports -> three captures each
const heavyPlay = 10; // expensive play function

const lines = [
  "import { BenchSurface } from './BenchSurface';",
  '',
  '// GENERATED by generate-scale.mjs. Do not edit by hand.',
  '//',
  '// S3: story-count scale with an intentionally skewed cost distribution so',
  '// count-balanced and cost-balanced worker assignment cannot coincide.',
  'const meta = {',
  "  title: 'Bench/Scale',",
  '  component: BenchSurface,',
  '};',
  '',
  'export default meta;',
  '',
];

let index = 0;
const name = prefix => `${prefix}${String((index += 1)).padStart(3, '0')}`;

for (let counter = 0; counter < light; counter += 1) {
  const exportName = name('Light');
  lines.push(
    `export const ${exportName} = { args: { label: '${exportName}', rows: 4, tone: ${counter % 7} } };`,
  );
}

for (let counter = 0; counter < delayed; counter += 1) {
  const exportName = name('Delayed');
  lines.push(
    `export const ${exportName} = {`,
    `  args: { label: '${exportName}', rows: 4, tone: ${counter % 7} },`,
    '  parameters: { screenshot: { delay: 150 } },',
    '};',
  );
}

for (let counter = 0; counter < multiVariant; counter += 1) {
  const exportName = name('Multi');
  lines.push(
    `export const ${exportName} = {`,
    `  args: { label: '${exportName}', rows: 6, tone: ${counter % 7} },`,
    '  parameters: {',
    '    screenshot: {',
    '      viewports: {',
    '        WIDE: { width: 1100, height: 700 },',
    '        NARROW: { width: 420, height: 900 },',
    '        SQUARE: { width: 700, height: 700 },',
    '      },',
    '    },',
    '  },',
    '};',
  );
}

for (let counter = 0; counter < heavyPlay; counter += 1) {
  const exportName = name('HeavyPlay');
  lines.push(
    `export const ${exportName} = {`,
    `  args: { label: '${exportName}', rows: 6, tone: ${counter % 7} },`,
    '  play: async () => {',
    '    await new Promise(resolve => setTimeout(resolve, 250));',
    '  },',
    '};',
  );
}

lines.push('');

const target = fileURLToPath(new URL('./Scale.stories.jsx', import.meta.url));
writeFileSync(target, lines.join('\n'), 'utf8');

const stories = index;
const captures = light + delayed + multiVariant * 3 + heavyPlay;
process.stdout.write(`Scale.stories.jsx: ${stories} stories, ${captures} expected captures\n`);

// A second set built to defeat index-based sharding.
//
// Round-robin assigns story i to shard i % totalShards, so it only stays
// balanced while cost is uncorrelated with sorted position. Here every fourth
// story is a three-viewport story, which puts all of them on one shard for a
// four-way split. Real projects hit this whenever a naming convention makes the
// expensive story of each component sort into the same position.
const skewGroups = 40;
const skewLines = [
  "import { BenchSurface } from './BenchSurface';",
  '',
  '// GENERATED by generate-scale.mjs. Do not edit by hand.',
  '//',
  '// S6: cost correlated with sorted index, which is the case index-based',
  '// sharding cannot balance.',
  'const meta = {',
  "  title: 'Bench/Skew',",
  '  component: BenchSurface,',
  '};',
  '',
  'export default meta;',
  '',
];

let skewIndex = 0;
for (let group = 0; group < skewGroups; group += 1) {
  for (let slot = 0; slot < 4; slot += 1) {
    const exportName = `Case${String((skewIndex += 1)).padStart(3, '0')}`;
    if (slot === 0) {
      skewLines.push(
        `export const ${exportName} = {`,
        `  args: { label: '${exportName}', rows: 6, tone: ${group % 7} },`,
        '  parameters: {',
        '    screenshot: {',
        '      viewports: {',
        '        WIDE: { width: 1100, height: 700 },',
        '        NARROW: { width: 420, height: 900 },',
        '        SQUARE: { width: 700, height: 700 },',
        '      },',
        '    },',
        '  },',
        '};',
      );
    } else {
      skewLines.push(
        `export const ${exportName} = { args: { label: '${exportName}', rows: 4, tone: ${group % 7} } };`,
      );
    }
  }
}
skewLines.push('');

writeFileSync(fileURLToPath(new URL('./Skew.stories.jsx', import.meta.url)), skewLines.join('\n'), 'utf8');
process.stdout.write(
  `Skew.stories.jsx: ${skewIndex} stories, ${skewGroups * 3 + skewGroups * 3} expected captures ` +
    `(${skewGroups} three-viewport stories every 4th)\n`,
);
